#!/usr/bin/env node
'use strict';

/**
 * Regenerates src/data/simplified-chars.js from the opencc-js STCharacters
 * dictionary. Characters that are also perfectly normal in Traditional Chinese
 * text (台, 后, 里, 面, 云, 万, …) are excluded, otherwise an already
 * Traditional subtitle would be misdetected as Simplified.
 */

const fs = require('fs');
const path = require('path');

const AMBIGUOUS = new Set(
	Array.from(
		'台后里面云万采郁冲卷志舍曲布准干松斗划系复种药号尽录历合朱朴谷注表制么咸范姜于叶沈' +
			'征凶伙熏厘咨雇据丑杰启弃'
	)
);

// `require.resolve('opencc-js')` -> node_modules/opencc-js/dist/umd/full.js
const packageRoot = path.join(path.dirname(require.resolve('opencc-js')), '..', '..');
const dictPath = path.join(packageRoot, 'dist', 'esm-lib', 'dict', 'STCharacters.js');
const source = fs.readFileSync(dictPath, 'utf8');
const dictionary = source.match(/"([\s\S]*)"/)[1];

/**
 * STCharacters also maps Traditional *variant* forms onto the regional standard
 * form (吃 -> 喫, 秘 -> 祕, 峰 -> 峯, 群 -> 羣 …). Those characters are perfectly
 * normal in Traditional text, so the TW/HK variant dictionaries are used to
 * recognise and drop them — otherwise an already-Traditional subtitle would be
 * misdetected as Simplified.
 */
function readDict(name) {
	const raw = fs.readFileSync(path.join(packageRoot, 'dist', 'esm-lib', 'dict', `${name}.js`), 'utf8');
	return raw.match(/"([\s\S]*)"/)[1];
}

const variantTargets = new Set();
for (const name of ['TWVariants', 'HKVariants']) {
	for (const entry of readDict(name).split('|')) {
		const value = entry.split(' ')[1];
		if (value && Array.from(value).length === 1) variantTargets.add(value);
	}
}

const chars = new Set();
for (const entry of dictionary.split('|')) {
	const key = entry.split(' ')[0];
	if (!key) continue;
	if (Array.from(key).length !== 1) continue;
	if (AMBIGUOUS.has(key)) continue;
	if (variantTargets.has(key)) continue;
	chars.add(key);
}

const output = Array.from(chars).sort().join('');
const target = path.join(__dirname, '..', 'src', 'data', 'simplified-chars.js');

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
	target,
	`'use strict';\n\n` +
		`// Generated by tools/build.js — do not edit by hand.\n` +
		`// Single characters that only occur in Simplified Chinese text, taken from\n` +
		`// the opencc-js STCharacters dictionary (ambiguous shared characters removed).\n` +
		`module.exports = ${JSON.stringify(output)};\n`
);

console.log(`simplified-chars.js: ${output.length} characters`);
